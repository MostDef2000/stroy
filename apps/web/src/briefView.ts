// R8 designer brief (#198): pure view-model helpers for BriefPage.
//
// No React and no runtime api import (api.ts only as `import type` — the
// compiled module must stay importable under Node, same ritual as copy.ts /
// sceneVariants.ts). Covers the four testable concerns of the brief page:
//
//   1. the privacy checklist (default checkbox states + inclusion filtering,
//      unchecked images are removed from the preview/print DOM),
//   2. furniture-intent grouping with id-free display labels,
//   3. section presence (a missing wire section never renders an empty
//      header),
//   4. the notes autosave persister (single debounced PATCH per quiet period)
//      and the print trigger (injectable stub in tests).
//
// Visible labels NEVER contain raw ids (#188 glossary rule): entity names
// fall back to the kind label, rooms to «Помещение», photos to «Фото N».

